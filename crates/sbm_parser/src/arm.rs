//! ARM cores by the `CPU implementer` and `CPU part` lines of `/proc/cpuinfo`,
//! named as `lscpu` names them.
//!
//! An arm64 kernel prints no `model name` at all, and a 32-bit one prints
//! `ARMv7 Processor rev 4 (v7l)`: an architecture and a revision, the same for
//! every core of a big.LITTLE CPU. The implementer and part are what tell the
//! cores apart, and `lscpu` is not on every machine that has them (BusyBox,
//! OpenWrt, NAS systems), so the table is here.
//!
//! The ids are util-linux's (`sys-utils/lscpu-arm.c`, GPL-2.0-or-later),
//! generated from it: regenerate when that table gains a core.

/// The vendor behind `CPU implementer` [implementer].
pub fn vendor(implementer: u32) -> Option<&'static str> {
    VENDORS
        .iter()
        .find(|(id, _)| *id == implementer)
        .map(|(_, name)| *name)
}

/// The core `CPU part` [part] of [implementer] is, as `lscpu` names it.
pub fn part(implementer: u32, part: u32) -> Option<&'static str> {
    PARTS
        .iter()
        .find(|(i, p, _)| *i == implementer && *p == part)
        .map(|(_, _, name)| *name)
}

/// What to call a core: its part, after its vendor unless that is ARM — whose
/// cores are known by the part alone (`Cortex-A55`, `Neoverse-N1`) — or the
/// part already says it (`Ampere-1`). Unknown parts keep their ids, so two
/// kinds of core still read as two.
pub fn core_name(implementer: u32, part_id: u32) -> String {
    let vendor = vendor(implementer);
    match (vendor, part(implementer, part_id)) {
        (Some("ARM"), Some(name)) => name.to_string(),
        (Some(vendor), Some(name)) if name.starts_with(vendor) => name.to_string(),
        (Some(vendor), Some(name)) => format!("{vendor} {name}"),
        (Some(vendor), None) => format!("{vendor} 0x{part_id:03x}"),
        (None, _) => format!("0x{implementer:02x} 0x{part_id:03x}"),
    }
}

